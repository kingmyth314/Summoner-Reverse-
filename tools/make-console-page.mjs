// Build docs/sum-exe/console.md from the generated command table (tools/console-commands.mjs --md).
import { readFileSync, writeFileSync, unlinkSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const tmp = join(repoRoot, "docs", "sum-exe", "console-commands.table.tmp");
const table = readFileSync(tmp, "utf8");
const count = table.split("\n").filter((l) => l.startsWith("| `")).length;
const page = `---
title: Console commands
parent: Sum.exe
nav_order: 6
---

# Console commands
{: .no_toc }

1. TOC
{:toc}

**Summary:** Sum.exe registers **${count} developer console commands** through static C++
objects, each built by one constructor, \`console_command::console_command\` (\`0x50a180\`).
Every command's callback and object are named in \`symbols/sum.symbols\` (\`cmd_<name>\`,
\`ccmd_<name>\`). Generated by \`node tools/console-commands.mjs\` (**observed**: 145 of 145
pattern sites call the same constructor).

## How commands are registered

Each command is a global \`console_command\` object built by a small static initialiser that
the C runtime runs at startup. Example for \`show_framerate\` (\`0x4323f0\`):

\`\`\`nasm
push 0x432410        ; callback  -> cmd_show_framerate
push 0x5931d0        ; "Toggles Gamewide_show_framerate"
push 0x5931c0        ; "show_framerate"
mov  ecx, 0x5fbfe8   ; the console_command object -> ccmd_show_framerate
call 0x50a180        ; console_command::console_command(name, description, callback)
ret
\`\`\`

The PC constructor takes three arguments. Summoner 2's takes four (name, description, type,
callback; see [Engine references](../reference/engine-references.md)), so the command type
is decided differently on PC (*inferred*; not yet analysed).

Callbacks are reached only through the object's function pointer, so Ghidra's
auto-analysis didn't create functions for most of them: 136 of the 145 were missing from
\`symbols/ghidra-functions.tsv\`.

Toggle callbacks read the argument flags that the console sets before calling. For
\`show_framerate\` (\`0x432410\`): flag \`0x40\` sets the variable to 1, \`0x80\` sets it to 0, and
\`0x01\` flips it; it then prints \`"<variable> is <state>"\` with \`sprintf\`.

## Using the commands

The descriptions name many internal variables ("Toggles Players_immortal", "Sets Gr_far_min"),
which makes this table a map of debug features. Timeslip's patch already binds commands to
keys (\`[console] k070=show_framerate\`); the planned
[custom key bindings](../roadmap.md#custom-key-bindings-for-player-actions) can use the same
route.

## All commands

${table}`;
writeFileSync(join(repoRoot, "docs", "sum-exe", "console.md"), page);
unlinkSync(tmp);
console.log(`wrote docs/sum-exe/console.md (${count} commands)`);
